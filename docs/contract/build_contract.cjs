// 本文の数字は全角にそろえる（手本の契約書と同じ）。URL・ドメインは半角のまま
const Z = (s) => s.replace(/[0-9]/g, (d) => String.fromCharCode(d.charCodeAt(0) + 0xfee0))

// BIZ UD明朝：Windows 10以降と macOS の両方に入っている明朝体（PDFにしたときも文字が欠けない）
const FONT = { ascii: 'BIZ UDMincho', eastAsia: 'BIZ UDMincho', hAnsi: 'BIZ UDMincho', cs: 'BIZ UDMincho' }
const run = (text, opts = {}) => new TextRun({ text, font: FONT, size: opts.size ?? 21, bold: opts.bold })
const para = (text, opts = {}) =>
  new Paragraph({
    children: [run(opts.raw ? text : Z(text), opts)],
    alignment: opts.align,
    spacing: { after: opts.after ?? 60, line: 340 },
    indent: opts.indent,
    keepNext: opts.keepNext,
    pageBreakBefore: opts.pageBreakBefore,
  })
// 別表・別紙は新しいページから（改ページだけの段落を置くと、前のページがちょうど埋まったときに白紙のページができる）
const title = (text, opts = {}) =>
  para(text, { size: 30, bold: true, align: AlignmentType.CENTER, after: 300, pageBreakBefore: opts.newPage })
const article = (text) => para(text, { bold: true, after: 60, keepNext: true })
// １．２．の項（ぶら下げ）
const item = (n, text) => para(`${n}．　${text}`, { indent: { left: 420, hanging: 420 } })
// （１）（２）の号
const sub = (n, text) => para(`（${n}）　${text}`, { indent: { left: 840, hanging: 520 } })
const blank = () => new Paragraph({ children: [run('')], spacing: { after: 60 } })

const border = { style: BorderStyle.SINGLE, size: 4, color: '808080' }
const cellBorders = { top: border, bottom: border, left: border, right: border }
function table(widths, rows) {
  return new Table({
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((cols, i) =>
      new TableRow({
        children: cols.map((c, j) =>
          new TableCell({
            width: { size: widths[j], type: WidthType.DXA },
            borders: cellBorders,
            shading: i === 0 ? { type: ShadingType.CLEAR, fill: 'EDEDED', color: 'auto' } : undefined,
            margins: { top: 60, bottom: 60, left: 100, right: 100 },
            children: [para(c, { bold: i === 0, after: 0 })],
          }),
        ),
      }),
    ),
  })
}

